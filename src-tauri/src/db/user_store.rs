/// Upserts a note pulled from cloud sync — parallel to
/// `upsert_synced_highlight`, kept separate from `create_note`/`update_note`
/// (the local-edit paths) so a plain local save can never accidentally
/// stamp a `remote_id` a pull hasn't actually confirmed. Matches the
/// existing local row by `remote_id` alone now — `verse_id` can no longer
/// identify "the" note for a conflict target once multiple notes can share
/// one (or have none at all). `deleted_at` is explicitly cleared for the
/// same reason `upsert_synced_highlight` clears it: a pull only ever sees
/// non-tombstoned remote rows.
pub fn upsert_synced_note(
    conn: &Connection,
    verse_id: Option<&str>,
    title: Option<&str>,
    content_text: &str,
    content_json: &str,
    remote_id: &str,
    created_at: &str,
    updated_at: &str,
) -> rusqlite::Result<()> {
    let existing_id: Option<i64> =
        conn.query_row("SELECT id FROM notes WHERE remote_id = ?1", [remote_id], |r| r.get(0)).optional()?;

    match existing_id {
        Some(id) => {
            conn.execute(
                "UPDATE notes SET verse_id = ?1, title = ?2, content_json = ?3, content_text = ?4, \
                 updated_at = ?5, deleted_at = NULL WHERE id = ?6",
                params![verse_id, title, content_json, content_text, updated_at, id],
            )?;
        }
        None => {
            conn.execute(
                "INSERT INTO notes (verse_id, title, content_json, content_text, remote_id, created_at, updated_at) \
                 VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)",
                params![verse_id, title, content_json, content_text, remote_id, created_at, updated_at],
            )?;
        }
    }
    Ok(())
}

/// Extracts unique `#hashtag` occurrences from note content, in first-seen
/// order — the note tag cloud (frontend) and each note's YAML frontmatter
/// `tags:` list (Obsidian export, below) both build on this.
pub fn extract_tags(content_text: &str) -> Vec<String> {
    static TAG_RE: OnceLock<regex::Regex> = OnceLock::new();
    let re = TAG_RE.get_or_init(|| regex::Regex::new(r"#([a-zA-Z0-9_-]+)").unwrap());
    let mut seen = std::collections::HashSet::new();
    let mut tags = Vec::new();
    for cap in re.captures_iter(content_text) {
        let tag = cap[1].to_string();
        if seen.insert(tag.clone()) {
            tags.push(tag);
        }
    }
    tags
}

fn sanitize_filename_component(s: &str) -> String {
    let cleaned: String = s
        .chars()
        .map(|c| if c.is_alphanumeric() || c == ' ' || c == '-' || c == '_' { c } else { '-' })
        .collect();
    let trimmed = cleaned.trim();
    if trimmed.is_empty() { "Untitled".to_string() } else { trimmed.to_string() }
}

/// One Markdown file per note, Obsidian-compatible (YAML frontmatter +
/// `#tags` inline, `[[WikiLinks]]` are already plain Obsidian syntax the
/// note body may contain as-is) — the command layer zips these together.
/// Filenames are de-duplicated by appending the note's id when two notes
/// would otherwise sanitize to the same name.
pub fn build_obsidian_notes(notes: &[Note]) -> Vec<(String, String)> {
    let mut used_names = std::collections::HashSet::new();
    notes
        .iter()
        .map(|n| {
            let record_key = n.verse_id.as_deref().unwrap_or("standalone");
            let title = n.title.clone().unwrap_or_else(|| record_key.to_string());
            let base = sanitize_filename_component(&title);
            let filename = if used_names.insert(base.clone()) {
                format!("{base}.md")
            } else {
                format!("{base}-{}.md", n.id)
            };
            let tags = extract_tags(&n.content_text);
            let tags_yaml = if tags.is_empty() {
                "[]".to_string()
            } else {
                format!("[{}]", tags.iter().map(|t| format!("\"{t}\"")).collect::<Vec<_>>().join(", "))
            };
            let content = format!(
                "---\ntitle: \"{}\"\nrecord_key: \"{}\"\ntags: {}\ncreated: {}\nupdated: {}\n---\n\n{}\n",
                title.replace('"', "'"),
                record_key,
                tags_yaml,
                n.created_at,
                n.updated_at,
                n.content_text,
            );
            (filename, content)
        })
        .collect()
}

/// All notes concatenated into a single Markdown document (the "Export
/// Markdown" — as opposed to "Export Obsidian Vault" — button).
pub fn build_markdown_export(notes: &[Note]) -> String {
    let mut out = String::new();
    for n in notes {
        let record_key = n.verse_id.as_deref().unwrap_or("Standalone");
        let title = n.title.clone().unwrap_or_else(|| record_key.to_string());
        out.push_str(&format!("## {title}\n\n"));
        out.push_str(&format!("*{} — updated {}*\n\n", record_key, n.updated_at));
        out.push_str(&n.content_text);
        out.push_str("\n\n---\n\n");
    }
    out
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

