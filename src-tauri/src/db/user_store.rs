/// Soft-delete: keeps the row (with its `remote_id`) so the next sync push
/// can carry a `deleted_at` tombstone to Supabase — a hard delete here would
/// have nothing left to push, and another device would never learn this
/// bookmark was removed. Re-bookmarking the same verse (`add_bookmark`)
/// clears `deleted_at`, reviving the same row rather than leaving a
/// dangling tombstone next to a fresh one.
pub fn remove_bookmark(conn: &Connection, verse_id: &str) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE bookmarks SET deleted_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now'), \
         updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE verse_id = ?1",
        [verse_id],
    )?;
    Ok(())
}

pub fn get_bookmarks(conn: &Connection) -> rusqlite::Result<Vec<Bookmark>> {
    let mut stmt = conn.prepare(&format!(
        "SELECT {BOOKMARK_COLUMNS} FROM bookmarks WHERE deleted_at IS NULL ORDER BY created_at DESC"
    ))?;
    let result = stmt.query_map([], row_to_bookmark)?.collect();
    result
}

/// Every bookmark row including tombstones — only the sync push path needs
/// these; everywhere else (the Bookmarks tab, search) a soft-deleted
/// bookmark should behave as gone.
pub fn get_bookmarks_for_sync(conn: &Connection) -> rusqlite::Result<Vec<Bookmark>> {
    let mut stmt = conn.prepare(&format!("SELECT {BOOKMARK_COLUMNS} FROM bookmarks ORDER BY created_at DESC"))?;
    let result = stmt.query_map([], row_to_bookmark)?.collect();
    result
}

/// Records the Supabase row id a bookmark is (or should be) synced under —
/// set once a device either generates a fresh id for a never-synced local
/// bookmark, or adopts the id of a row pulled down from another device, so
/// every later push upserts the same remote row instead of forking it.
pub fn set_bookmark_remote_id(conn: &Connection, verse_id: &str, remote_id: &str) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE bookmarks SET remote_id = ?1 WHERE verse_id = ?2",
        params![remote_id, verse_id],
    )?;
    Ok(())
}

/// Applies a deletion that happened on another device: soft-deletes
/// whichever local bookmark (if any) carries this `remote_id`. A no-op if
/// this device has never synced that row (nothing to retract).
pub fn apply_bookmark_tombstone(conn: &Connection, remote_id: &str, deleted_at: &str) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE bookmarks SET deleted_at = ?1 WHERE remote_id = ?2",
        params![deleted_at, remote_id],
    )?;
    Ok(())
}

/// Records the Supabase `vb_bookmark_collections.id` every bookmark
/// currently sharing this `tag` should push under, so the next push upserts
/// the one real remote collection instead of each device re-deriving (and
/// thereby forking) its own id for the same-named collection. Updates every
/// bookmark with this tag at once, since the collection id is shared by
/// construction (v3 has no separate collections table — see `rename_bookmark_collection`).
pub fn set_bookmark_remote_collection_id(conn: &Connection, tag: &str, remote_collection_id: &str) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE bookmarks SET remote_collection_id = ?1 WHERE tag = ?2",
        params![remote_collection_id, tag],
    )?;
    Ok(())
}

/// Bookmarks have no dedicated collections table — `tag` doubles as the
/// collection name (a bookmark with `tag = NULL` is "Uncategorized"), so
/// "renaming a collection" is a bulk update of every bookmark sharing that
/// tag rather than a row in some separate table.
pub fn rename_bookmark_collection(conn: &Connection, old_tag: &str, new_tag: &str) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE bookmarks SET tag = ?1, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE tag = ?2",
        params![new_tag, old_tag],
    )?;
    Ok(())
}

/// "Deleting a collection" clears the tag on its members (moving them to
/// Uncategorized) rather than deleting the bookmarks themselves.
pub fn clear_bookmark_collection(conn: &Connection, tag: &str) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE bookmarks SET tag = NULL, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE tag = ?1",
        params![tag],
    )?;
    Ok(())
}

pub fn move_bookmark_to_collection(conn: &Connection, verse_id: &str, tag: Option<&str>) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE bookmarks SET tag = ?1, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE verse_id = ?2",
        params![tag, verse_id],
    )?;
    Ok(())
}

