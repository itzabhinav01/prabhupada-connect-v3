const NOTE_COLUMNS: &str = "id, verse_id, title, content_json, content_text, created_at, updated_at, remote_id, deleted_at";

/// Always inserts a new row — unlike the old one-note-per-verse scheme,
/// there's no existing row to upsert onto by `verse_id` anymore (multiple
/// notes can share a verse, and a standalone note has no `verse_id` at
/// all), so "create" and "edit" are necessarily two different operations
/// now (see `update_note`).
pub fn create_note(conn: &Connection, n: NewNote) -> rusqlite::Result<Note> {
    conn.execute(
        "INSERT INTO notes (verse_id, title, content_json, content_text) VALUES (?1, ?2, ?3, ?4)",
        params![n.verse_id, n.title, n.content_json, n.content_text],
    )?;
    let id = conn.last_insert_rowid();
    conn.query_row(&format!("SELECT {NOTE_COLUMNS} FROM notes WHERE id = ?1"), [id], row_to_note)
}

/// Edits an existing note's content in place, identified by its own `id` —
/// `verse_id` can no longer identify "the" note to update since a verse may
/// have several. Reviving a previously soft-deleted note (rather than
/// leaving a dangling tombstone next to fresh content) is intentional here
/// too, same reasoning as `add_bookmark`'s `deleted_at = NULL`.
pub fn update_note(
    conn: &Connection,
    id: i64,
    title: Option<&str>,
    content_json: &str,
    content_text: &str,
) -> rusqlite::Result<Note> {
    conn.execute(
        "UPDATE notes SET title = ?1, content_json = ?2, content_text = ?3, deleted_at = NULL, \
         updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = ?4",
        params![title, content_json, content_text, id],
    )?;
    conn.query_row(&format!("SELECT {NOTE_COLUMNS} FROM notes WHERE id = ?1"), [id], row_to_note)
}

/// Soft-delete: keeps the row (with its `remote_id`) so the next sync push
/// can carry a `deleted_at` tombstone to Supabase — see `remove_bookmark`'s
/// doc comment for why a hard `DELETE` here would silently fail to sync the
/// deletion to any other device. Identified by `id`, not `verse_id` (no
/// longer unique, and `None` for standalone notes).
pub fn delete_note(conn: &Connection, id: i64) -> rusqlite::Result<()> {
    conn.execute("UPDATE notes SET deleted_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = ?1", [id])?;
    Ok(())
}

