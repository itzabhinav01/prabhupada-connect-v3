/// Opens (creating if necessary) the read-write user data database and runs
/// the idempotent schema migration. WAL mode is enabled here — unlike the
/// read-only corpus, this database is actually written to by the app, so WAL
/// lets reads and writes proceed without blocking each other.
/// True if `table` already has a column named `column` — SQLite's
/// `ALTER TABLE ... ADD COLUMN` has no `IF NOT EXISTS` form, so additive
/// migrations on a database that predates this column must check first
/// (safe against injection: `table`/`column` are always our own hardcoded
/// literals below, never user input).
fn column_exists(conn: &Connection, table: &str, column: &str) -> rusqlite::Result<bool> {
    let mut stmt = conn.prepare(&format!("PRAGMA table_info({table})"))?;
    let exists = stmt
        .query_map([], |row| row.get::<_, String>(1))?
        .filter_map(|r| r.ok())
        .any(|name| name == column);
    Ok(exists)
}

pub fn open_and_migrate(path: &Path) -> rusqlite::Result<Connection> {
    let conn = Connection::open(path)?;
    // `journal_mode` always returns the resulting mode as a result row, even
    // when "set" via PRAGMA — pragma_update accounts for that, whereas plain
    // execute_batch rejects statements that return rows.
    conn.pragma_update_and_check(None, "journal_mode", "WAL", |_row| Ok(()))?;
    conn.pragma_update(None, "foreign_keys", "ON")?;
    conn.execute_batch(SCHEMA)?;

    // Additive migrations for columns introduced after the tables above
    // first shipped — `CREATE TABLE IF NOT EXISTS` alone doesn't add them to
    // an already-existing database.
    if !column_exists(&conn, "highlights", "field")? {
        conn.execute_batch("ALTER TABLE highlights ADD COLUMN field TEXT")?;
    }
    if !column_exists(&conn, "notes", "title")? {
        conn.execute_batch("ALTER TABLE notes ADD COLUMN title TEXT")?;
    }
    // Stable cross-device identity for cloud sync — v2's `UserBookmark.Id` is
    // a GUID assigned at creation, independent of `verse_id`; the local
    // autoincrement `id` can't fill that role (it's per-database, so two
    // devices' bookmarks for the same verse would get different Supabase
    // rows). `remote_id` is generated by the sync layer on first push (or
    // adopted from a pulled row) and reused on every push after that.
    if !column_exists(&conn, "bookmarks", "remote_id")? {
        conn.execute_batch("ALTER TABLE bookmarks ADD COLUMN remote_id TEXT")?;
    }
    // Soft-delete: v2 pushes a `deleted_at` tombstone when a bookmark is
    // removed, so another device's next pull knows to retract it too. A
    // hard `DELETE` here would push nothing on the next sync, leaving v2
    // (or any other device) holding a bookmark this one already removed —
    // it would look like the deletion silently didn't sync.
    if !column_exists(&conn, "bookmarks", "deleted_at")? {
        conn.execute_batch("ALTER TABLE bookmarks ADD COLUMN deleted_at TEXT")?;
    }
    // Same stable cross-device identity + tombstone pattern as bookmarks
    // above, now extended to notes and highlights — without `remote_id`,
    // every push synthesized a fresh id from local data (verse_id for
    // notes, a verse+range+color composite for highlights) instead of
    // reusing the row's real Supabase id, so every device's push forked its
    // own duplicate remote row. Without `deleted_at`, `delete_note`/
    // `delete_highlight` hard-deleted, leaving nothing to push as a
    // tombstone — a deletion on one device never reached any other.
    if !column_exists(&conn, "notes", "remote_id")? {
        conn.execute_batch("ALTER TABLE notes ADD COLUMN remote_id TEXT")?;
    }
    if !column_exists(&conn, "notes", "deleted_at")? {
        conn.execute_batch("ALTER TABLE notes ADD COLUMN deleted_at TEXT")?;
    }
    if !column_exists(&conn, "highlights", "remote_id")? {
        conn.execute_batch("ALTER TABLE highlights ADD COLUMN remote_id TEXT")?;
    }
    if !column_exists(&conn, "highlights", "deleted_at")? {
        conn.execute_batch("ALTER TABLE highlights ADD COLUMN deleted_at TEXT")?;
    }
    // v3 has no local collections table (a bookmark's `tag` string doubles
    // as its collection's name), so there's nowhere to persist the stable
    // Supabase id of the collection a bookmark belongs to — every push used
    // to derive a fresh id by hashing the tag name instead, which collides
    // with nothing a pre-existing v2 collection (random GUID) ever used,
    // producing a second, duplicate-named collection in Supabase (and then
    // in v2) on every sync. Storing the real id once it's known (pulled, or
    // discovered on first push) and reusing it from then on fixes that.
    if !column_exists(&conn, "bookmarks", "remote_collection_id")? {
        conn.execute_batch("ALTER TABLE bookmarks ADD COLUMN remote_collection_id TEXT")?;
    }
    // Unlike notes/highlights, bookmarks never got an `updated_at` column —
    // every mutation (collection rename, tag change, soft-delete) left the
    // row's only timestamp at its original `created_at`. The sync push sent
    // that unchanged value, so v2's incremental pull (`updated_at >
    // watermark`) never saw the edit at all.
    if !column_exists(&conn, "bookmarks", "updated_at")? {
        conn.execute_batch(
            "ALTER TABLE bookmarks ADD COLUMN updated_at TEXT;
             UPDATE bookmarks SET updated_at = created_at WHERE updated_at IS NULL;",
        )?;
    }

    // v2 supports standalone (not verse-anchored) research notes and
    // multiple notes on the same verse; the original schema's
    // `verse_id TEXT NOT NULL UNIQUE` ruled out both, silently dropping any
    // such note pulled from Supabase and capping every verse at one local
    // note. Neither constraint can be altered in place in SQLite, so this
    // rebuilds the table — guarded on `verse_id` still being NOT NULL so it
    // only ever runs once per database.
    if notes_verse_id_is_not_null(&conn)? {
        conn.execute_batch(
            "CREATE TABLE notes_new (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                verse_id TEXT,
                title TEXT,
                content_json TEXT NOT NULL,
                content_text TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
                updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
                remote_id TEXT,
                deleted_at TEXT
             );
             INSERT INTO notes_new (id, verse_id, title, content_json, content_text, created_at, updated_at, remote_id, deleted_at)
                SELECT id, verse_id, title, content_json, content_text, created_at, updated_at, remote_id, deleted_at FROM notes;
             DROP TABLE notes;
             ALTER TABLE notes_new RENAME TO notes;
             CREATE INDEX IF NOT EXISTS idx_notes_verse ON notes(verse_id);",
        )?;
    }

    Ok(conn)
}

/// True if `notes.verse_id` still has its original `NOT NULL` constraint —
/// the one-shot guard for the standalone-notes/multi-note-per-verse
/// migration above (SQLite's `PRAGMA table_info` has no equivalent flag for
/// `UNIQUE`, but that constraint was introduced and is removed in the exact
/// same rebuild, so this alone is a reliable "already migrated?" check).
fn notes_verse_id_is_not_null(conn: &Connection) -> rusqlite::Result<bool> {
    let mut stmt = conn.prepare("PRAGMA table_info(notes)")?;
    let rows = stmt.query_map([], |row| Ok((row.get::<_, String>(1)?, row.get::<_, i64>(3)?)))?;
    for row in rows {
        let (name, notnull) = row?;
        if name == "verse_id" {
            return Ok(notnull != 0);
        }
    }
    Ok(false)
}

