#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Highlight {
    pub id: i64,
    pub verse_id: String,
    pub color: String,
    pub text_range_start: i64,
    pub text_range_end: i64,
    pub selected_text: String,
    /// Which verse field the selection was made in — `"translation"` |
    /// `"synonyms"` | `"purport"` | `None` for highlights made before this
    /// column existed. Matches v2's Supabase `vb_highlights.field` values.
    pub field: Option<String>,
    pub created_at: String,
    pub updated_at: String,
    /// Supabase `vb_highlights.id` this highlight last synced under — null
    /// until the first push (or pull) assigns one. See `supabaseSync.ts`.
    pub remote_id: Option<String>,
    /// Set when soft-deleted locally; only present on rows from
    /// `get_all_highlights_for_sync` (`get_all_highlights`/
    /// `get_highlights_for_verse` never return one).
    pub deleted_at: Option<String>,
}

#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct NewHighlight {
    pub verse_id: String,
    pub color: String,
    pub text_range_start: i64,
    pub text_range_end: i64,
    pub selected_text: String,
    #[serde(default)]
    pub field: Option<String>,
}

fn row_to_highlight(row: &rusqlite::Row) -> rusqlite::Result<Highlight> {
    Ok(Highlight {
        id: row.get(0)?,
        verse_id: row.get(1)?,
        color: row.get(2)?,
        text_range_start: row.get(3)?,
        text_range_end: row.get(4)?,
        selected_text: row.get(5)?,
        field: row.get(6)?,
        created_at: row.get(7)?,
        updated_at: row.get(8)?,
        remote_id: row.get(9)?,
        deleted_at: row.get(10)?,
    })
}

const HIGHLIGHT_COLUMNS: &str = "id, verse_id, color, text_range_start, text_range_end, selected_text, field, created_at, updated_at, remote_id, deleted_at";

pub fn save_highlight(conn: &Connection, h: NewHighlight) -> rusqlite::Result<Highlight> {
    conn.execute(
        "INSERT INTO highlights (verse_id, color, text_range_start, text_range_end, selected_text, field) \
         VALUES (?1, ?2, ?3, ?4, ?5, ?6)",
        params![h.verse_id, h.color, h.text_range_start, h.text_range_end, h.selected_text, h.field],
    )?;
    let id = conn.last_insert_rowid();
    conn.query_row(
        &format!("SELECT {HIGHLIGHT_COLUMNS} FROM highlights WHERE id = ?1"),
        [id],
        row_to_highlight,
    )
}

/// Soft-delete: keeps the row (with its `remote_id`) so the next sync push
/// can carry a `deleted_at` tombstone to Supabase — see `remove_bookmark`'s
/// doc comment for why a hard `DELETE` here would silently fail to sync the
/// deletion to any other device.
pub fn delete_highlight(conn: &Connection, id: i64) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE highlights SET deleted_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') WHERE id = ?1",
        [id],
    )?;
    Ok(())
}

pub fn get_highlights_for_verse(conn: &Connection, verse_id: &str) -> rusqlite::Result<Vec<Highlight>> {
    let mut stmt = conn.prepare(&format!(
        "SELECT {HIGHLIGHT_COLUMNS} FROM highlights WHERE verse_id = ?1 AND deleted_at IS NULL ORDER BY text_range_start"
    ))?;
    let result = stmt.query_map([verse_id], row_to_highlight)?.collect();
    result
}

pub fn get_all_highlights(conn: &Connection) -> rusqlite::Result<Vec<Highlight>> {
    let mut stmt = conn.prepare(&format!(
        "SELECT {HIGHLIGHT_COLUMNS} FROM highlights WHERE deleted_at IS NULL ORDER BY created_at DESC"
    ))?;
    let result = stmt.query_map([], row_to_highlight)?.collect();
    result
}

/// Every highlight including soft-deleted ones — only the sync push path
/// needs these (to carry a tombstone up); everywhere else `get_all_highlights`
/// (active-only) is the right call.
pub fn get_all_highlights_for_sync(conn: &Connection) -> rusqlite::Result<Vec<Highlight>> {
    let mut stmt =
        conn.prepare(&format!("SELECT {HIGHLIGHT_COLUMNS} FROM highlights ORDER BY created_at DESC"))?;
    let result = stmt.query_map([], row_to_highlight)?.collect();
    result
}

/// Records the Supabase row id a highlight is (or should be) synced under —
/// same role as `set_bookmark_remote_id`, keyed by the local autoincrement
/// `id` since highlights have no other stable local identity.
pub fn set_highlight_remote_id(conn: &Connection, id: i64, remote_id: &str) -> rusqlite::Result<()> {
    conn.execute("UPDATE highlights SET remote_id = ?1 WHERE id = ?2", params![remote_id, id])?;
    Ok(())
}

/// Applies a deletion that happened on another device: soft-deletes
/// whichever local highlight (if any) carries this `remote_id`. A no-op if
/// this device has never synced that row (nothing to retract).
pub fn apply_highlight_tombstone(conn: &Connection, remote_id: &str, deleted_at: &str) -> rusqlite::Result<()> {
    conn.execute(
        "UPDATE highlights SET deleted_at = ?1 WHERE remote_id = ?2",
        params![deleted_at, remote_id],
    )?;
    Ok(())
}

/// Upserts a highlight pulled from cloud sync. Highlights have no single
/// natural-key column locally (unlike notes/bookmarks' `UNIQUE(verse_id)`),
/// so this matches on the same composite key the sync layer used to use as
/// the remote row's id (`verse_id` + range + color) to stay idempotent
/// across repeated pulls instead of duplicating the row every time — and
/// additionally keys on `remote_id` once a row has one, since the
/// composite key is no longer what the remote row is actually pushed under
/// (see `supabaseSync.ts`'s `pushAll`). `deleted_at` is explicitly cleared:
/// a pull only ever sees non-tombstoned remote rows, so one existing here
/// means it's current and should un-delete a stale local soft-delete,
/// matching `add_bookmark`'s same `deleted_at = NULL` precedent.
/// `remote_id` is `None` for a non-sync caller (the `.vdbbackup` local file
/// importer) that has no Supabase row to associate yet — it leaves any
/// existing `remote_id` untouched (`COALESCE`) rather than clobbering a
/// highlight's real sync identity back to unset.
#[allow(clippy::too_many_arguments)]
pub fn upsert_synced_highlight(
    conn: &Connection,
    verse_id: &str,
    color: &str,
    text_range_start: i64,
    text_range_end: i64,
    selected_text: &str,
    field: Option<&str>,
    created_at: &str,
    updated_at: &str,
    remote_id: Option<&str>,
) -> rusqlite::Result<()> {
    let existing_id: Option<i64> = conn
        .query_row(
            "SELECT id FROM highlights WHERE (?1 IS NOT NULL AND remote_id = ?1) \
             OR (verse_id = ?2 AND text_range_start = ?3 AND text_range_end = ?4 AND color = ?5)",
            params![remote_id, verse_id, text_range_start, text_range_end, color],
            |r| r.get(0),
        )
        .optional()?;

    match existing_id {
        Some(id) => {
            conn.execute(
                "UPDATE highlights SET selected_text = ?1, field = ?2, updated_at = ?3, remote_id = COALESCE(?4, remote_id), deleted_at = NULL WHERE id = ?5",
                params![selected_text, field, updated_at, remote_id, id],
            )?;
        }
        None => {
            conn.execute(
                "INSERT INTO highlights (verse_id, color, text_range_start, text_range_end, selected_text, field, created_at, updated_at, remote_id) \
                 VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, ?9)",
                params![verse_id, color, text_range_start, text_range_end, selected_text, field, created_at, updated_at, remote_id],
            )?;
        }
    }
    Ok(())
}

